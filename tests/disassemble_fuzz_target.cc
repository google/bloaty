// Fuzz target for bloaty's disassembly path (src/disassemble.cc and the ELF
// symbol lookup behind it).
//
// Threat model: --disassemble=FUNCTION makes bloaty locate FUNCTION in the
// binary's symbol tables and hand the function's raw bytes (located through
// program-header translation) to the capstone disassembler.  Both the binary
// and the function name are attacker-influenced.  This path is mutually
// exclusive with data-source scans, so the plain fuzz_target never reaches it.
//
// Harness shape: component harness.  The fuzzed input is split on a "$FN$"
// marker: the part before the marker is the scanned binary, the part after it
// (up to the first NUL) is the function name.  Seeds are generated by
// generate_disassemble_seeds.py: a minimal ELF64 whose .symtab contains a
// FUNC symbol "fn", plus the matching name part.

#include <cstring>
#include <string_view>

#include "bloaty.h"

using std::string_view;

namespace bloaty {

namespace {

constexpr char kInputFilename[] = "input_file";
constexpr char kSplitMarker[] = "$FN$";
constexpr size_t kMaxNameLength = 128;

}  // namespace

class SplitInputFile : public InputFile {
 public:
  SplitInputFile(string_view name, string_view data)
      : InputFile(std::string(name)) {
    data_ = data;
  }

  bool TryOpen(std::string_view /* filename */,
               std::unique_ptr<InputFile>& /* file */) override {
    return false;
  }
};

class BinaryFileFactory : public InputFileFactory {
 public:
  explicit BinaryFileFactory(string_view data) : data_(data) {}

 private:
  string_view data_;

  std::unique_ptr<InputFile> OpenFile(
      const std::string& filename) const override {
    return std::unique_ptr<InputFile>(new SplitInputFile(filename, data_));
  }
};

}  // namespace bloaty

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  if (size == 0) {
    return 0;
  }

  string_view input(reinterpret_cast<const char*>(data), size);
  size_t marker = input.find(bloaty::kSplitMarker);
  string_view binary =
      input.substr(0, marker == string_view::npos ? size : marker);
  string_view name_part =
      marker == string_view::npos
          ? string_view()
          : input.substr(marker + std::strlen(bloaty::kSplitMarker));

  // The function name runs to the first NUL, bounded, so capstone work stays
  // proportional to the binary part and not to unbounded names.
  if (name_part.size() > bloaty::kMaxNameLength) {
    name_part = name_part.substr(0, bloaty::kMaxNameLength);
  }
  size_t nul = name_part.find('\0');
  if (nul != string_view::npos) {
    name_part = name_part.substr(0, nul);
  }
  if (name_part.empty()) {
    return 0;
  }

  bloaty::RollupOutput output;
  bloaty::Options options;
  std::string error;
  options.set_disassemble_function(std::string(name_part));
  options.add_filename(bloaty::kInputFilename);

  bloaty::BinaryFileFactory factory(binary);
  bloaty::BloatyMain(options, factory, &output, &error);

  return 0;
}
