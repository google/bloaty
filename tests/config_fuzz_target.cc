// Fuzz target for bloaty's command-line option parsing and configuration
// files (src/bloaty.cc DoParseOptions, the -c protobuf TextFormat config, and
// the RollupOutput CSV/TSV/pretty printers).
//
// Threat model: bloaty is a CLI tool.  Its argv parser accepts dozens of
// option/value combinations, its `-c` configs are protobuf TextFormat files
// that define custom data sources with re2 regex rewrites applied to symbol
// names, and the output formatters print attacker-influenced strings.  None of
// this is exercised by the plain fuzz_target, which uses a fixed option set.
//
// Harness shape: option matrix plus a text-language frontend.  The fuzzed
// input is split on a "$CFG$" marker.  Before the marker: NUL-separated argv
// tokens.  After the marker: the config file text.  The `-c` option reads its
// file through std::ifstream, so the config part is written to a temporary
// real file per iteration.  Seeds are generated by generate_config_seeds.py.

#include <fcntl.h>
#include <unistd.h>

#include <cerrno>
#include <cstdio>
#include <cstring>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

#include "bloaty.h"

using std::string_view;

namespace bloaty {

namespace {

constexpr char kInputFilename[] = "input_file";
constexpr char kSplitMarker[] = "$CFG$";

}  // namespace

class SingleInputFile : public InputFile {
 public:
  SingleInputFile(string_view name, string_view data)
      : InputFile(std::string(name)) {
    data_ = data;
  }

  bool TryOpen(std::string_view /* filename */,
               std::unique_ptr<InputFile>& /* file */) override {
    return false;
  }
};

// Serves the fuzzed binary content for every filename.
class SingleFileFactory : public InputFileFactory {
 public:
  explicit SingleFileFactory(string_view data) : data_(data) {}

 private:
  string_view data_;

  std::unique_ptr<InputFile> OpenFile(
      const std::string& filename) const override {
    return std::unique_ptr<InputFile>(new SingleInputFile(filename, data_));
  }
};

// Writes the fuzzed config to a real temporary file so that bloaty's `-c`
// handling can open it with std::ifstream; always removes it again.
class TempConfigFile {
 public:
  explicit TempConfigFile(string_view content) {
    char path[] = "/tmp/bloaty_config_fuzz_XXXXXX";
    fd_ = mkstemp(path);
    if (fd_ < 0) {
      return;
    }
    path_ = path;
    const char* p = content.data();
    size_t remaining = content.size();
    while (remaining > 0) {
      ssize_t written = write(fd_, p, remaining);
      if (written <= 0) {
        if (written < 0 && errno == EINTR) {
          continue;
        }
        break;
      }
      p += written;
      remaining -= static_cast<size_t>(written);
    }
  }

  ~TempConfigFile() {
    if (fd_ >= 0) {
      close(fd_);
    }
    if (!path_.empty()) {
      unlink(path_.c_str());
    }
  }

  bool ok() const { return fd_ >= 0; }
  const std::string& path() const { return path_; }

 private:
  int fd_ = -1;
  std::string path_;
};

}  // namespace bloaty

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  if (size == 0) {
    return 0;
  }

  string_view input(reinterpret_cast<const char*>(data), size);
  size_t marker = input.find(bloaty::kSplitMarker);
  string_view argv_part =
      input.substr(0, marker == string_view::npos ? size : marker);
  string_view config_part =
      marker == string_view::npos
          ? string_view()
          : input.substr(marker + std::strlen(bloaty::kSplitMarker));

  bloaty::TempConfigFile config(config_part);
  if (!config.ok()) {
    return 0;
  }

  // Fixed tokens so that a scan always happens: config file, then input file.
  std::vector<std::string> args;
  args.push_back("bloaty");
  size_t start = 0;
  while (start < argv_part.size()) {
    size_t end = argv_part.find('\0', start);
    if (end == string_view::npos) {
      end = argv_part.size();
    }
    if (end > start) {
      args.emplace_back(argv_part.substr(start, end - start));
    }
    start = end + 1;
  }
  args.push_back("-c");
  args.push_back(config.path());
  args.push_back(bloaty::kInputFilename);

  std::vector<char*> argv;
  for (std::string& arg : args) {
    argv.push_back(&arg[0]);
  }
  int argc = static_cast<int>(argv.size());
  char** argv_ptr = argv.data();

  // The scanned binary is the raw fuzz input itself.
  bloaty::SingleFileFactory factory(input);
  bloaty::Options options;
  bloaty::OutputOptions output_options;
  std::string error;

  // skip_unknown=true so that mutated junk options still reach the scanner
  // below; the parser's own error paths stay covered through fuzzed values of
  // known options.
  if (bloaty::ParseOptions(true, &argc, &argv_ptr, &options, &output_options,
                           &error)) {
    bloaty::RollupOutput output;
    if (bloaty::BloatyMain(options, factory, &output, &error)) {
      std::stringstream out_stream;
      output.Print(output_options, &out_stream);
    }
  }

  return 0;
}
