// Fuzz target for the source map parser (src/source_map.cc).
//
// Threat model: a JS source map (.map) file is attacker-controlled input that
// bloaty consumes when it scans a WebAssembly module whose "sourceMappingURL"
// custom section matches the --source-map argument.  The map is parsed with a
// hand-rolled brace/quote reader and its "mappings" string is decoded with a
// custom Base64 VLQ decoder; parsed segments index into the "sources" vector
// with unchecked indices, so malformed maps reach memory-safety-sensitive
// code.  Neither the parser nor the VLQ decoder is exercised by the plain
// fuzz_target, because it never sets a source map.
//
// Harness shape: bytes-into-parser with a two-file split.  The fuzzed input is
// split on a "$SM$" marker: the part before the marker is the scanned
// WebAssembly binary, the part after it is the source map text.  The input
// file factory below serves each virtual file with its own content.
//
// The seeds are generated by generate_source_map_seeds.py so that the binary
// part is a structurally valid WASM module carrying a "sourceMappingURL"
// custom section whose content is "sourcemap_file": that is the name under
// which this harness registers the source map, which is the lookup path bloaty
// uses to attach the map as the module's debug file.

#include <cstring>
#include <string_view>

#include "bloaty.h"

using std::string_view;

namespace bloaty {

namespace {

constexpr char kWasmFilename[] = "input_file";
constexpr char kSourceMapFilename[] = "sourcemap_file";
constexpr char kSplitMarker[] = "$SM$";

}  // namespace

class SplitInputFile : public InputFile {
 public:
  SplitInputFile(string_view name, string_view data)
      : InputFile(std::string(name)) {
    data_ = data;
  }

  bool TryOpen(std::string_view /* filename */,
               std::unique_ptr<InputFile>& /* file */) override {
    return false;
  }
};

// Serves the scanned binary for every filename except the source map name,
// which gets the source map content.
class SplitInputFileFactory : public InputFileFactory {
 public:
  SplitInputFileFactory(string_view input, string_view sourcemap)
      : input_(input), sourcemap_(sourcemap) {}

 private:
  string_view input_;
  string_view sourcemap_;

  std::unique_ptr<InputFile> OpenFile(
      const std::string& filename) const override {
    if (filename == kSourceMapFilename) {
      return std::unique_ptr<InputFile>(
          new SplitInputFile(filename, sourcemap_));
    }
    return std::unique_ptr<InputFile>(new SplitInputFile(filename, input_));
  }
};

// Source maps are processed through the compileunits and inlines data sources
// only (see SourceMapObjectFile::ProcessFileToSink).
void RunBloatyOnSourceMap(const InputFileFactory& factory,
                          const char* data_source) {
  bloaty::RollupOutput output;
  bloaty::Options options;
  std::string error;
  options.add_filename(kWasmFilename);
  options.add_source_map(kSourceMapFilename);
  options.add_data_source(data_source);
  bloaty::BloatyMain(options, factory, &output, &error);
}

}  // namespace bloaty

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  if (size == 0) {
    return 0;
  }

  string_view input(reinterpret_cast<const char*>(data), size);
  size_t marker = input.find(bloaty::kSplitMarker);
  string_view binary =
      input.substr(0, marker == string_view::npos ? size : marker);
  string_view sourcemap =
      marker == string_view::npos
          ? string_view()
          : input.substr(marker + std::strlen(bloaty::kSplitMarker));

  bloaty::SplitInputFileFactory factory(binary, sourcemap);
  bloaty::RunBloatyOnSourceMap(factory, "compileunits");
  bloaty::RunBloatyOnSourceMap(factory, "inlines");

  return 0;
}
